import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

const password = process.env.GMV_E2E_PASSWORD || JSON.parse(fs.readFileSync(path.resolve('../data/test-environment.json'), 'utf8')).admin_password
test('dictionary CRUD and bilingual search → weighted prompt translation → original copy → delete fallback', async ({ page, context }) => {
  test.setTimeout(90000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByLabel('用户名', { exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '进入工作空间' }).click()
  await page.getByRole('button', { name: 'Tag 翻译', exact: true }).click()
  const search = page.getByLabel('搜索 Tag 翻译')
  await search.fill('白发')
  await expect(page.locator('.translation-row').first()).toContainText('白')
  await search.fill('white_hair')
  await expect(page.locator('.translation-row').first()).toContainText(/white[ _]hair/)
  await page.getByLabel('翻译分类筛选').selectOption('人物-头发')
  await expect(page.locator('.translation-row').first()).toContainText('人物-头发')
  await page.screenshot({ path: '../test-artifacts/v03-dictionary.png', fullPage: true })
  await page.getByRole('button', { name: '清除分类', exact: true }).click()
  const searched = page.waitForResponse(response => response.url().includes('/translations?q=gmv') && response.request().method() === 'GET')
  await search.fill('gmv translation demo')
  // Repeated local runs clean up only this synthetic test dictionary entry.
  await searched
  await expect(page.locator('.translation-count')).not.toContainText('查询中')
  const previous = page.getByRole('button', { name: '删除翻译 gmv translation demo', exact: true })
  if (await previous.count()) { page.once('dialog', dialog => dialog.accept()); await previous.click(); await expect(previous).toHaveCount(0) }
  await page.getByRole('button', { name: '添加翻译', exact: true }).click()
  await page.getByLabel('英文 Tag', { exact: true }).fill('gmv translation demo')
  await page.getByLabel('中文翻译', { exact: true }).fill('创作验证词')
  await page.getByLabel('翻译所属分类', { exact: true }).fill('自定义-创作')
  await page.getByRole('button', { name: '保存翻译', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await search.fill('创作验证')
  await expect(page.locator('.translation-row')).toContainText('gmv translation demo')
  await page.getByRole('button', { name: '编辑翻译 gmv translation demo', exact: true }).click()
  await page.getByLabel('中文翻译', { exact: true }).fill('创作演示词')
  await page.getByRole('button', { name: '保存翻译', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await search.fill('gmv trans')
  await expect(page.locator('.translation-row')).toContainText('创作演示词')
  await page.getByRole('button', { name: '导入文件', exact: true }).click()
  await page.getByLabel('选择上传文件', { exact: true }).setInputFiles(path.resolve('../backend/tests/fixtures/translations.png'))
  await page.getByRole('button', { name: '提交导入' }).click()
  await expect(page.getByRole('status')).toContainText('导入任务已提交')
  await page.getByRole('button', { name: /全部资产/ }).click()
  await expect(page.getByRole('button', { name: '查看 translations.png', exact: true })).toBeVisible({ timeout: 20000 })
  await page.getByRole('button', { name: '查看 translations.png', exact: true }).click()
  await page.getByRole('button', { name: '标签', exact: true }).click()
  await page.getByRole('switch', { name: '提示词翻译' }).check()
  const tokens = page.locator('.token-picker')
  await expect(tokens.getByRole('button', { name: '创作演示词', exact: true })).toBeVisible()
  await expect(tokens.getByRole('button', { name: 'unknown demo phrase', exact: true })).toBeVisible()
  await expect(tokens.getByRole('button', { name: /\(.*:1\.2\)/ })).toContainText(/蓝/)
  await tokens.getByRole('button', { name: '创作演示词', exact: true }).click()
  await page.getByRole('button', { name: /新建分组/ }).click()
  await page.getByRole('button', { name: '复制本组', exact: true }).last().click()
  await expect.poll(() => page.evaluate(() => navigator.clipboard.readText())).toBe('gmv translation demo')
  await page.screenshot({ path: '../test-artifacts/v03-translated-prompt.png', fullPage: true })
  await page.getByRole('switch', { name: '提示词翻译' }).uncheck()
  await expect(tokens.getByRole('button', { name: 'gmv translation demo', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: 'Tag 翻译', exact: true }).click()
  await search.fill('gmv translation demo')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除翻译 gmv translation demo', exact: true }).click()
  await expect(page.getByRole('heading', { name: '没有匹配的翻译' })).toBeVisible()
  await page.getByRole('button', { name: /全部资产/ }).click()
  await page.getByRole('button', { name: '查看 translations.png', exact: true }).click()
  await page.getByRole('button', { name: '标签', exact: true }).click()
  await page.getByRole('switch', { name: '提示词翻译' }).check()
  await expect(page.locator('.token-picker').getByRole('button', { name: 'gmv translation demo', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '打开导航' }).click()
  await page.getByRole('button', { name: 'Tag 翻译', exact: true }).click()
  await page.getByLabel('搜索 Tag 翻译').fill('白发')
  await expect(page.locator('.translation-row').first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect(errors).toEqual([])
})
